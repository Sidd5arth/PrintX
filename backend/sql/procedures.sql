-- printX DB2 stored procedures

-- Invoice header by id or number
CREATE OR REPLACE PROCEDURE PRINTX.GET_INVOICE_HEADER (IN P_ID VARCHAR(32))
  RESULT SETS 1
  LANGUAGE SQL
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT *
    FROM PRINTX.INVOICE_HEADER
    WHERE INVOICE_ID = P_ID OR INVOICE_NUMBER = P_ID;
  OPEN C1;
END;

-- Invoice line items
CREATE OR REPLACE PROCEDURE PRINTX.GET_INVOICE_LINES (IN P_ID VARCHAR(32))
  RESULT SETS 1
  LANGUAGE SQL
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT L.*
    FROM PRINTX.INVOICE_LINE L
    INNER JOIN PRINTX.INVOICE_HEADER H ON H.INVOICE_ID = L.INVOICE_ID
    WHERE H.INVOICE_ID = P_ID OR H.INVOICE_NUMBER = P_ID
    ORDER BY L.LINE_NO;
  OPEN C1;
END;

-- Receipt header
CREATE OR REPLACE PROCEDURE PRINTX.GET_RECEIPT_HEADER (IN P_ID VARCHAR(32))
  RESULT SETS 1
  LANGUAGE SQL
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT *
    FROM PRINTX.RECEIPT_HEADER
    WHERE RECEIPT_ID = P_ID OR RECEIPT_NUMBER = P_ID;
  OPEN C1;
END;

-- Receipt line items
CREATE OR REPLACE PROCEDURE PRINTX.GET_RECEIPT_LINES (IN P_ID VARCHAR(32))
  RESULT SETS 1
  LANGUAGE SQL
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT L.*
    FROM PRINTX.RECEIPT_LINE L
    INNER JOIN PRINTX.RECEIPT_HEADER H ON H.RECEIPT_ID = L.RECEIPT_ID
    WHERE H.RECEIPT_ID = P_ID OR H.RECEIPT_NUMBER = P_ID
    ORDER BY L.LINE_NO;
  OPEN C1;
END;
