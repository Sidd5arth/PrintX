-- printX DB2 schema (IBM DB2 LUW)
-- Schema: PRINTX

CREATE SCHEMA PRINTX;

CREATE TABLE PRINTX.INVOICE_HEADER (
  INVOICE_ID        VARCHAR(32)   NOT NULL PRIMARY KEY,
  INVOICE_NUMBER    VARCHAR(32)   NOT NULL,
  STATUS            VARCHAR(20)   NOT NULL,
  CURRENCY          CHAR(3)       NOT NULL DEFAULT 'USD',
  ISSUE_DATE        DATE          NOT NULL,
  DUE_DATE          DATE,
  PAID_DATE         DATE,
  COMPANY_NAME      VARCHAR(120)  NOT NULL,
  COMPANY_ADDR1     VARCHAR(120),
  COMPANY_ADDR2     VARCHAR(120),
  COMPANY_CITY      VARCHAR(60),
  COMPANY_STATE     VARCHAR(20),
  COMPANY_POSTAL    VARCHAR(20),
  COMPANY_COUNTRY   VARCHAR(60),
  COMPANY_PHONE     VARCHAR(40),
  COMPANY_EMAIL     VARCHAR(120),
  COMPANY_TAX_ID    VARCHAR(40),
  CUSTOMER_ID       VARCHAR(32)   NOT NULL,
  CUSTOMER_NAME     VARCHAR(120)  NOT NULL,
  CUSTOMER_ADDR1    VARCHAR(120),
  CUSTOMER_ADDR2    VARCHAR(120),
  CUSTOMER_CITY     VARCHAR(60),
  CUSTOMER_STATE    VARCHAR(20),
  CUSTOMER_POSTAL   VARCHAR(20),
  CUSTOMER_COUNTRY  VARCHAR(60),
  CUSTOMER_EMAIL    VARCHAR(120),
  CUSTOMER_PHONE    VARCHAR(40),
  BILLTO_NAME       VARCHAR(120),
  BILLTO_ADDR1      VARCHAR(120),
  BILLTO_CITY       VARCHAR(60),
  BILLTO_STATE      VARCHAR(20),
  BILLTO_POSTAL     VARCHAR(20),
  BILLTO_COUNTRY    VARCHAR(60),
  SHIPTO_NAME       VARCHAR(120),
  SHIPTO_ADDR1      VARCHAR(120),
  SHIPTO_CITY       VARCHAR(60),
  SHIPTO_STATE      VARCHAR(20),
  SHIPTO_POSTAL     VARCHAR(20),
  SHIPTO_COUNTRY    VARCHAR(60),
  PO_NUMBER         VARCHAR(40),
  PAYMENT_TERMS     VARCHAR(40),
  NOTES             VARCHAR(1000),
  SUBTOTAL          DECIMAL(15,2) NOT NULL DEFAULT 0,
  DISCOUNT_TOTAL    DECIMAL(15,2) NOT NULL DEFAULT 0,
  TAX_TOTAL         DECIMAL(15,2) NOT NULL DEFAULT 0,
  SHIPPING          DECIMAL(15,2) NOT NULL DEFAULT 0,
  GRAND_TOTAL       DECIMAL(15,2) NOT NULL DEFAULT 0,
  AMOUNT_PAID       DECIMAL(15,2) NOT NULL DEFAULT 0,
  BALANCE_DUE       DECIMAL(15,2) NOT NULL DEFAULT 0
);

CREATE TABLE PRINTX.INVOICE_LINE (
  INVOICE_ID    VARCHAR(32)   NOT NULL,
  LINE_NO       INTEGER       NOT NULL,
  SKU           VARCHAR(40),
  DESCRIPTION   VARCHAR(255)  NOT NULL,
  QUANTITY      DECIMAL(12,3) NOT NULL,
  UNIT          VARCHAR(10),
  UNIT_PRICE    DECIMAL(15,2) NOT NULL,
  DISCOUNT_PCT  DECIMAL(5,2)  NOT NULL DEFAULT 0,
  TAX_PCT       DECIMAL(5,2)  NOT NULL DEFAULT 0,
  AMOUNT        DECIMAL(15,2) NOT NULL,
  PRIMARY KEY (INVOICE_ID, LINE_NO),
  FOREIGN KEY (INVOICE_ID) REFERENCES PRINTX.INVOICE_HEADER (INVOICE_ID)
);

CREATE TABLE PRINTX.RECEIPT_HEADER (
  RECEIPT_ID       VARCHAR(32)   NOT NULL PRIMARY KEY,
  RECEIPT_NUMBER   VARCHAR(32)   NOT NULL,
  STATUS           VARCHAR(20)   NOT NULL,
  CURRENCY         CHAR(3)       NOT NULL DEFAULT 'USD',
  RECEIPT_DATE     DATE          NOT NULL,
  PAYMENT_METHOD   VARCHAR(40),
  PAYMENT_REF      VARCHAR(60),
  INVOICE_ID       VARCHAR(32),
  INVOICE_NUMBER   VARCHAR(32),
  COMPANY_NAME     VARCHAR(120)  NOT NULL,
  COMPANY_ADDR1    VARCHAR(120),
  COMPANY_ADDR2    VARCHAR(120),
  COMPANY_CITY     VARCHAR(60),
  COMPANY_STATE    VARCHAR(20),
  COMPANY_POSTAL   VARCHAR(20),
  COMPANY_COUNTRY  VARCHAR(60),
  COMPANY_PHONE    VARCHAR(40),
  COMPANY_EMAIL    VARCHAR(120),
  COMPANY_TAX_ID   VARCHAR(40),
  CUSTOMER_ID      VARCHAR(32)   NOT NULL,
  CUSTOMER_NAME    VARCHAR(120)  NOT NULL,
  CUSTOMER_ADDR1   VARCHAR(120),
  CUSTOMER_CITY    VARCHAR(60),
  CUSTOMER_STATE   VARCHAR(20),
  CUSTOMER_POSTAL  VARCHAR(20),
  CUSTOMER_COUNTRY VARCHAR(60),
  CUSTOMER_EMAIL   VARCHAR(120),
  CASHIER          VARCHAR(80),
  TERMINAL_ID      VARCHAR(40),
  NOTES            VARCHAR(1000),
  SUBTOTAL         DECIMAL(15,2) NOT NULL DEFAULT 0,
  TAX_TOTAL        DECIMAL(15,2) NOT NULL DEFAULT 0,
  TIP              DECIMAL(15,2) NOT NULL DEFAULT 0,
  GRAND_TOTAL      DECIMAL(15,2) NOT NULL DEFAULT 0,
  AMOUNT_TENDERED  DECIMAL(15,2) NOT NULL DEFAULT 0,
  CHANGE_DUE       DECIMAL(15,2) NOT NULL DEFAULT 0
);

CREATE TABLE PRINTX.RECEIPT_LINE (
  RECEIPT_ID   VARCHAR(32)   NOT NULL,
  LINE_NO      INTEGER       NOT NULL,
  DESCRIPTION  VARCHAR(255)  NOT NULL,
  QUANTITY     DECIMAL(12,3) NOT NULL,
  UNIT_PRICE   DECIMAL(15,2) NOT NULL,
  AMOUNT       DECIMAL(15,2) NOT NULL,
  PRIMARY KEY (RECEIPT_ID, LINE_NO),
  FOREIGN KEY (RECEIPT_ID) REFERENCES PRINTX.RECEIPT_HEADER (RECEIPT_ID)
);

CREATE INDEX PRINTX.IX_INV_CUSTOMER ON PRINTX.INVOICE_HEADER (CUSTOMER_ID, ISSUE_DATE);
CREATE INDEX PRINTX.IX_RCP_CUSTOMER ON PRINTX.RECEIPT_HEADER (CUSTOMER_ID, RECEIPT_DATE);
